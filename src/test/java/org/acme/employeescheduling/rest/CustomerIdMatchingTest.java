package org.acme.employeescheduling.rest;

import static io.restassured.RestAssured.given;
import static org.hamcrest.Matchers.is;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ThreadLocalRandom;

import jakarta.inject.Inject;
import jakarta.persistence.EntityManager;

import org.acme.employeescheduling.persistence.LocationEntity;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;

import io.quarkus.narayana.jta.QuarkusTransaction;
import io.quarkus.test.junit.QuarkusTest;
import io.quarkus.test.security.TestSecurity;
import io.restassured.http.ContentType;

/**
 * @brief Guards the location/customer comparison in both assignment resources against the
 *        boxed-Integer trap.
 *
 * @details {@code locations.customer_id} and {@code customers.id} are both {@code Integer}, so
 *          {@code !=} compares references instead of values. The two ids the check compares come
 *          from two separate rows, therefore from two separate boxes, and boxes are identical only
 *          inside the JVM's Integer cache (-128..127). A freshly seeded database therefore passes
 *          and a database whose customer ids have grown past 127 rejects every visit with
 *          ASSIGNMENT_LOCATION_CUSTOMER_MISMATCH — the same value, two boxes. The customer below
 *          is inserted with an explicit id far above the cache, which is the cheapest way to
 *          reproduce that state without seeding a thousand rows.
 */
@QuarkusTest
@TestSecurity(user = "test-admin", roles = {"ADMIN", "CAPOSALA"})
@EnabledIfSystemProperty(named = "quarkus.test.profile", matches = "test-(sqlite|postgresql)")
class CustomerIdMatchingTest {

    /**
     * @brief Above the Integer cache (-128..127) and unique per run.
     *
     * @details The SQLite test database survives between runs, so a fixed id would collide with
     *          the row the previous run left behind - the same trap the other fixtures hit with
     *          {@code employees.code}. Random and high is enough for a value that only has to be
     *          outside the cache.
     */
    private final int customerId = ThreadLocalRandom.current().nextInt(1_000, Integer.MAX_VALUE);
    private static final String DATE = "2026-07-09";

    @Inject
    EntityManager em;

    private int createStructure() {
        return given().contentType(ContentType.JSON)
                .body(Map.of("id", 0, "name", "MVZ Cache " + UUID.randomUUID(),
                        "address", "Teststrasse 1", "phone", "+49 000"))
                .when().post("/structures").then().statusCode(201)
                .extract().jsonPath().getInt("id");
    }

    private int createLocation(int structureId) {
        return QuarkusTransaction.requiringNew().call(() -> {
            LocationEntity location = new LocationEntity();
            location.name = "MVZ Nord " + UUID.randomUUID();
            location.structureId = structureId;
            location.active = true;
            location.persist();
            return location.id;
        });
    }

    /**
     * @brief Inserts the customer with an explicit id instead of letting the sequence choose one.
     *
     * @details Both engines allow it — {@code INTEGER PRIMARY KEY AUTOINCREMENT} on SQLite and
     *          {@code GENERATED BY DEFAULT AS IDENTITY} (not ALWAYS) on PostgreSQL — but Panache
     *          cannot: {@code @GeneratedValue(strategy = IDENTITY)} makes Hibernate drop a preset
     *          id and use the one the database assigned. Hence the native insert.
     */
    private void createCustomerWithExplicitId(int structureId, int id) {
        QuarkusTransaction.requiringNew().run(() -> em.createNativeQuery(
                "INSERT INTO customers (id, structure_id, code, name, address, phone, active, "
                        + "default_start_time, default_duration_minutes, recurrence_pattern, restrictions) "
                        + "VALUES (?1, ?2, ?3, ?4, '', '', 1, '08:00', 120, '', '')")
                .setParameter(1, id)
                .setParameter(2, structureId)
                .setParameter(3, "K-" + UUID.randomUUID().toString().substring(0, 8))
                .setParameter(4, "Pflegeheim Sonnental " + UUID.randomUUID())
                .executeUpdate());
    }

    private void attachLocationToCustomer(int locationId, int customerId) {
        QuarkusTransaction.requiringNew().run(() -> {
            LocationEntity location = LocationEntity.findById(locationId);
            location.customerId = customerId;
        });
    }

    private static Map<String, Object> requirement(String role, int headcount) {
        Map<String, Object> line = new HashMap<>();
        line.put("role", role);
        line.put("headcount", headcount);
        return line;
    }

    private Map<String, Object> assignmentBody(int locationId) {
        Map<String, Object> body = new HashMap<>();
        body.put("id", 0);
        body.put("customerId", customerId);
        body.put("locationId", locationId);
        body.put("title", "Wundversorgung");
        body.put("service", "Wundversorgung");
        body.put("assignmentDate", DATE);
        body.put("startTime", "08:00");
        body.put("durationMinutes", 120);
        body.put("priority", 1);
        body.put("status", "FLEXIBLE");
        body.put("fixedTime", false);
        body.put("requirements", List.of(requirement("PHYSICIAN", 1)));
        return body;
    }

    private Map<String, Object> seriesBody(int locationId) {
        Map<String, Object> body = new HashMap<>();
        body.put("customerId", customerId);
        body.put("locationId", locationId);
        body.put("title", "Wundversorgung");
        body.put("service", "Wundversorgung");
        body.put("startTime", "08:00");
        body.put("durationMinutes", 120);
        body.put("priority", 2);
        body.put("fixedTime", true);
        body.put("patternType", "WEEKLY");
        body.put("weekdays", "1");
        body.put("nth", 0);
        body.put("effectiveFrom", "2026-07-06");
        body.put("effectiveTo", "2026-12-31");
        body.put("active", true);
        body.put("requirements", List.of(requirement("PHYSICIAN", 1)));
        return body;
    }

    @Test
    void assignmentIsAcceptedForACustomerIdAboveTheIntegerCache() {
        int structureId = createStructure();
        int locationId = createLocation(structureId);
        createCustomerWithExplicitId(structureId, customerId);
        attachLocationToCustomer(locationId, customerId);

        given().contentType(ContentType.JSON)
                .body(assignmentBody(locationId))
                .when().post("/assignments?structureId={s}", structureId)
                .then().statusCode(201)
                .body("customerId", is(customerId));
    }

    @Test
    void seriesIsAcceptedForACustomerIdAboveTheIntegerCache() {
        int structureId = createStructure();
        int locationId = createLocation(structureId);
        createCustomerWithExplicitId(structureId, customerId);
        attachLocationToCustomer(locationId, customerId);

        given().contentType(ContentType.JSON)
                .body(seriesBody(locationId))
                .when().post("/assignments/series?structureId={s}", structureId)
                .then().statusCode(201)
                .body("customerId", is(customerId));
    }
}
