-- Recurring customer assignments (templates that generate concrete occurrences).
--
-- Planning a month by hand is not viable: a care centre runs roughly twenty visits a day, so a
-- month is several hundred assignments. The series is the template — customer, location, time of
-- day, duration, team composition and a recurrence rule — and the planner generates the concrete
-- occurrences for a period from it. An occurrence is a normal customer_assignments row with
-- series_id set, so the solver, the materialised positions and the save path stay exactly as they
-- are. Nothing here introduces a second planner.
--
-- The rule is data, not a free-text note: pattern_type + weekdays + nth are what the generator
-- evaluates. customers.recurrence_pattern stays what it was — a preference recorded by the
-- planner — and is deliberately not read by the generator, because parsing a note would silently
-- invent occurrences the planner never asked for.
--
-- Exceptions are stored per occurrence date rather than by mutating the series: cancelling one
-- Tuesday must not change every other Tuesday, and re-generating a period must not resurrect the
-- cancelled occurrence.

CREATE TABLE assignment_series (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structure_id INTEGER NOT NULL DEFAULT 1,
    customer_id INTEGER NOT NULL,
    location_id INTEGER NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    service TEXT NOT NULL DEFAULT '',
    start_time TEXT NOT NULL DEFAULT '08:00',
    duration_minutes INTEGER NOT NULL DEFAULT 480,
    priority INTEGER NOT NULL DEFAULT 2 CHECK (priority IN (1, 2, 3)),
    fixed_time INTEGER NOT NULL DEFAULT 0 CHECK (fixed_time IN (0, 1)),
    notes TEXT NOT NULL DEFAULT '',
    -- WEEKLY (every week), BIWEEKLY (every second week, anchored on effective_from),
    -- MONTHLY_NTH_WEEKDAY (the nth weekday of the month, e.g. the first Monday).
    pattern_type TEXT NOT NULL DEFAULT 'WEEKLY',
    -- ISO weekday numbers, 1 = Monday … 7 = Sunday, comma separated. A weekly series may hold
    -- several (Monday and Thursday = one visit each).
    weekdays TEXT NOT NULL DEFAULT '1',
    -- 1..5 for MONTHLY_NTH_WEEKDAY, 0 when unused.
    nth INTEGER NOT NULL DEFAULT 0 CHECK (nth >= 0 AND nth <= 5),
    effective_from TEXT NOT NULL,
    effective_to TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT '',
    FOREIGN KEY (structure_id) REFERENCES structures(id) ON DELETE CASCADE,
    FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE,
    FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE CASCADE
);

CREATE INDEX idx_assignment_series_window
    ON assignment_series (structure_id, effective_from);

-- Team composition of the series, copied into every occurrence it generates. Same shape as
-- assignment_requirements, so an occurrence is created through the existing write path.
CREATE TABLE assignment_series_requirements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id INTEGER NOT NULL,
    role TEXT NOT NULL DEFAULT 'MEDICAL_ASSISTANT',
    skill_id INTEGER,
    headcount INTEGER NOT NULL DEFAULT 1 CHECK (headcount >= 1),
    FOREIGN KEY (series_id) REFERENCES assignment_series(id) ON DELETE CASCADE,
    FOREIGN KEY (skill_id) REFERENCES skills(id) ON DELETE SET NULL
);

CREATE INDEX idx_assignment_series_requirements_series
    ON assignment_series_requirements (series_id);

-- Per-occurrence exception. CANCELLED drops the occurrence's positions but keeps the assignment
-- row as the audit trail; MOVED shifts that occurrence to new_date/new_start_time. Either way the
-- series is untouched, and the generator refuses to recreate the original date.
CREATE TABLE assignment_exceptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id INTEGER NOT NULL,
    occurrence_date TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'CANCELLED',
    new_date TEXT NOT NULL DEFAULT '',
    new_start_time TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT '',
    UNIQUE (series_id, occurrence_date),
    FOREIGN KEY (series_id) REFERENCES assignment_series(id) ON DELETE CASCADE
);

-- Occurrence lookups during generation: "which dates of this series already exist".
CREATE INDEX idx_customer_assignments_series
    ON customer_assignments (series_id, assignment_date);
